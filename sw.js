// Cache fail app supaya buka laju & tetap jalan bila line lemah.
// Naikkan VERSION setiap kali fail app berubah.
const VERSION = "v5";
const CACHE = `hookaffiliate-${VERSION}`;
const SHELL = [
  "./", "index.html", "style.css", "app.js", "hooks.js", "frames.js", "manifest.webmanifest",
  "icons/icon-192.png", "icons/icon-512.png",
];

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Fail sendiri: network dulu (dapat versi terbaru), fallback ke cache bila offline.
// Request lain (API Anthropic, Google Fonts) tak diusik.
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(req)
      .then((res) => {
        const copy = res.clone();
        caches.open(CACHE).then((c) => c.put(req, copy));
        return res;
      })
      .catch(() => caches.match(req).then((r) => r || caches.match("index.html")))
  );
});
